// Copies the original demo's member stylesheets into apps/member/src/styles/source/, in the demo's build order and
// with the demo's own scoping (scripts/build.mjs in the clone kit), so the member app gets the same cascade:
//
//   product.css            every rule prefixed with #favorite-hearts-product (html, body and :root become the id)
//   overrides.css          unscoped, as in the demo
//   contrast.css           unscoped
//   combined-overrides.css unscoped
//   design-system.css      unscoped ("final presentation authority")
//   base.css               the demo build's trailing html/body rule
//
// The demo's Tailwind layer is not copied: the member app already compiles Tailwind 4 with the same tokens. These
// files are generated: do not edit them. Repository-owned corrections (accessibility fixes, decided differences) go
// in src/styles/parity.css, which loads after them.
//
//   node scripts/ui-parity/port-css.mjs <path to Favorite-Hearts-Complete-UI-Clone-Kit>
//
// Development tool only. It uses postcss from the workspace's node_modules (a Tailwind dependency).
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const kit = process.argv[2];
if (!kit) {
  console.error('Usage: node scripts/ui-parity/port-css.mjs <clone kit folder>');
  process.exit(1);
}
const product = join(kit, 'original-ui-source/Favorite-Hearts-Integrated/product');
const out = fileURLToPath(new URL('../../apps/member/src/styles/source/', import.meta.url));

// Verbatim from the demo's scripts/build.mjs.
function scope(css, id) {
  const ast = postcss.parse(css);
  ast.walkRules((rule) => {
    for (let p = rule.parent; p; p = p.parent) {
      if (p.type === 'rule' || (p.type === 'atrule' && /keyframes/.test(p.name))) return;
    }
    rule.selectors = rule.selectors.map((s) => (['html', 'body', ':root'].includes(s) ? id : id + ' ' + s.replace(/:root/g, '')));
  });
  return ast.toString();
}

const header = (from) =>
  `/* Generated by scripts/ui-parity/port-css.mjs from the original demo (${from}). Do not edit: corrections go in\n` +
  `   src/styles/parity.css. */\n`;

await mkdir(out, { recursive: true });
const files = [
  ['product.css', 'preview/product.css', (css) => scope(css, '#favorite-hearts-product')],
  ['overrides.css', 'preview/overrides.css', (css) => css],
  ['contrast.css', 'preview/contrast.css', (css) => css],
  ['combined-overrides.css', 'preview/combined-overrides.css', (css) => css],
  ['design-system.css', 'app/design-system.css', (css) => css],
];
for (const [name, from, transform] of files) {
  const css = await readFile(join(product, from), 'utf8');
  await writeFile(join(out, name), header(`product/${from}`) + transform(css));
  console.log(name, css.length);
}
await writeFile(
  join(out, 'base.css'),
  header('scripts/build.mjs, trailing rule') +
    'html,body{margin:0;min-height:100%;font-family:Inter,Arial,sans-serif}*{box-sizing:border-box}' +
    '#favorite-hearts-product{min-height:100dvh}#favorite-hearts-product .ma-entry{min-height:100dvh}\n',
);
console.log('base.css');
